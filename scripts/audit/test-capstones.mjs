#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import ts from 'typescript';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(process.cwd());
const ZIPS_DIR = path.join(ROOT, 'public/capstones');
const TMP_CAP = path.join(ROOT, '.tmp-capstone-check');
const TMP_TS = path.join(ROOT, '.tmp-capstone-ts');

function resolvePython() {
  const venvPy = path.join(ROOT, '.venv-audit/bin/python');
  if (fs.existsSync(venvPy)) return venvPy;
  return 'python3';
}

function loadLevelsValidator() {
  fs.rmSync(TMP_TS, { recursive: true, force: true });
  fs.mkdirSync(TMP_TS, { recursive: true });
  const program = ts.createProgram([path.join(ROOT, 'src/data/levels.ts')], {
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.CommonJS,
    moduleResolution: ts.ModuleResolutionKind.Node10,
    esModuleInterop: true,
    skipLibCheck: true,
    outDir: TMP_TS,
    rootDir: path.join(ROOT, 'src'),
    baseUrl: ROOT,
    paths: { '@/*': ['src/*'] },
  });
  const emitRes = program.emit();
  const diags = ts.getPreEmitDiagnostics(program).concat(emitRes.diagnostics);
  if (diags.length > 0) {
    throw new Error('Failed compiling src/data/levels.ts for capstone verification');
  }
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(full);
      else if (ent.name.endsWith('.js')) {
        let code = fs.readFileSync(full, 'utf8');
        code = code.replace(/require\("@\/([^"]+)"\)/g, (_, target) => {
          let rel = path.relative(path.dirname(full), path.join(TMP_TS, target)).replace(/\\/g, '/');
          if (!rel.startsWith('.')) rel = './' + rel;
          return `require("${rel}")`;
        });
        fs.writeFileSync(full, code, 'utf8');
      }
    }
  };
  walk(TMP_TS);
  return require(path.join(TMP_TS, 'data/levels.js'));
}

export function runCapstoneVerification() {
  const py = resolvePython();
  execFileSync('node', [path.join(ROOT, 'scripts/build-zips.mjs')], { stdio: 'inherit' });

  const { validateCapstoneEvidence } = loadLevelsValidator();
  fs.rmSync(TMP_CAP, { recursive: true, force: true });
  fs.mkdirSync(TMP_CAP, { recursive: true });

  const zips = fs.readdirSync(ZIPS_DIR).filter((f) => f.endsWith('.zip')).sort();
  assert.equal(zips.length, 7, `Expected 7 capstone zips, found ${zips.length}: ${zips.join(', ')}`);

  const results = [];
  for (const zipName of zips) {
    const projectId = zipName.replace(/\.zip$/, '');
    const zipPath = path.join(ZIPS_DIR, zipName);
    execFileSync(py, ['-m', 'zipfile', '-e', zipPath, TMP_CAP], { stdio: 'pipe' });

    const projDir = path.join(TMP_CAP, projectId);
    assert.ok(fs.existsSync(projDir), `Extracted dir missing for ${projectId}`);

    // Run offline tests and validator via Makefile
    execFileSync('make', ['test', `PYTHON=${py}`], { cwd: projDir, stdio: 'pipe' });
    execFileSync('make', ['check', `PYTHON=${py}`], { cwd: projDir, stdio: 'pipe' });

    const evPath = path.join(projDir, 'evidence.json');
    assert.ok(fs.existsSync(evPath), `${projectId}/evidence.json not generated by make check`);
    const rawEv = fs.readFileSync(evPath, 'utf8');
    const check = validateCapstoneEvidence(
      projectId,
      `https://github.com/ai-eng/${projectId}`,
      `https://${projectId}.example.com`,
      rawEv
    );
    assert.equal(check.valid, true, `${projectId} failed validateCapstoneEvidence: ${check.error}`);
    results.push({ projectId, testsPassed: check.parsedSummary.testsPassed, mode: check.parsedSummary.mode });
  }

  fs.rmSync(TMP_CAP, { recursive: true, force: true });
  fs.rmSync(TMP_TS, { recursive: true, force: true });
  return results;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const res = runCapstoneVerification();
  console.log(`Verified ${res.length}/7 capstone starter repos (make test + make check -> valid evidence.json):`);
  for (const r of res) {
    console.log(`  - ${r.projectId}: ${r.testsPassed} tests passed (${r.mode})`);
  }
}
